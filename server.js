import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import morgan from 'morgan';
import { connectDB } from './config/db.js';
import api from './routes/api.js';
const app=express();
app.use(cors({origin:process.env.CLIENT_URL?.split(',')||true}));
app.use(express.json({limit:'1mb'})); app.use(morgan('dev'));
app.get('/api/health',(req,res)=>res.json({status:'ok',app:"AYTI'S Academy API"}));
app.use('/api',api);
app.use((req,res)=>res.status(404).json({message:'API route not found'}));
app.use((err,req,res,next)=>{console.error(err);const status=err.name==='ValidationError'||err.name==='CastError'?400:err.code===11000?409:500;res.status(status).json({message:err.code===11000?'A record with this unique value already exists':err.message||'Server error'})});
const port=process.env.PORT||5000;
connectDB().then(()=>app.listen(port,()=>console.log(`API running on http://localhost:${port}`))).catch(e=>{console.error('Database connection failed:',e.message);process.exit(1)});
